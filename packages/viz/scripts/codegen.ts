/**
 * Anchor extraction (ADR-005). Reads the display sources in `sources/<algorithmId>/` and
 * produces `src/generated/sources.ts` with `// @anchor` / `# @anchor` comments stripped and an
 * anchor → line-number index per language.
 *
 *   pnpm codegen          regenerate
 *   pnpm codegen --check  fail if the committed file is stale (CI)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractAnchors } from '../src/anchors';
import type { CodeSource, Lang } from '../src/types';

const root = fileURLToPath(new URL('..', import.meta.url));
const sourcesDir = join(root, 'sources');
const outFile = join(root, 'src', 'generated', 'sources.ts');

const FILES: Record<string, Lang> = {
  'main.cpp': 'cpp',
  'Main.java': 'java',
  'main.py': 'python',
  'main.ts': 'ts',
};

const out: Record<string, Partial<Record<Lang, CodeSource>>> = {};
const errors: string[] = [];

for (const algo of readdirSync(sourcesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()) {
  const entry: Partial<Record<Lang, CodeSource>> = {};
  for (const [file, lang] of Object.entries(FILES)) {
    const path = join(sourcesDir, algo, file);
    if (!existsSync(path)) continue;
    try {
      entry[lang] = { lang, ...extractAnchors(readFileSync(path, 'utf8'), lang) };
    } catch (err) {
      errors.push(`${algo}/${file}: ${(err as Error).message}`);
    }
  }
  out[algo] = entry;
}

if (errors.length) {
  console.error(`anchor extraction failed:\n  ${errors.join('\n  ')}`);
  process.exit(1);
}

const body =
  `// AUTO-GENERATED by scripts/codegen.ts from sources/ — do not edit. Run \`pnpm codegen\`.\n` +
  `import type { CodeSource, Lang } from '../types';\n\n` +
  `export const SOURCES: Record<string, Partial<Record<Lang, CodeSource>>> = ${JSON.stringify(out, null, 2)};\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== body) {
    console.error('src/generated/sources.ts is stale. Run `pnpm codegen` and commit the result.');
    process.exit(1);
  }
  console.log(`sources up to date (${Object.keys(out).length} algorithms)`);
} else {
  writeFileSync(outFile, body);
  console.log(`wrote ${Object.keys(out).length} algorithm sources → src/generated/sources.ts`);
}
